create extension if not exists vector with schema extensions;

-- 1) 기사·공시·데이터 (수집 DB)
create table if not exists articles (
  id            bigint generated by default as identity primary key,
  url_key       text not null unique,          -- 중복 비교용 주소
  url           text not null,                 -- 원문 주소 (그대로 보존)
  title         text not null,
  source        text not null,
  source_trust  smallint not null default 3,   -- 매체 기본 신뢰도 1~5
  source_grade  text not null default '해설',  -- 공시 / 통신사 / 해설 / 커뮤니티
  tier          text not null default 'T2',    -- T1~T4
  market        text not null default 'KR',    -- KR / US / GLOBAL
  feed_kind     text,                          -- rss / gnews / naver / dart / sec ...
  published_at  timestamptz not null,
  snippet       text,
  status        text not null default 'new',   -- new / published / skipped
  title_ko      text,
  summary       text,
  key_points    jsonb default '[]'::jsonb,
  tags          jsonb default '[]'::jsonb,
  tickers       jsonb default '[]'::jsonb,     -- [{"market":"KR","code":"005930","name":"삼성전자"}]
  sentiment     text,                          -- 호재 / 악재 / 중립 (기사 논조)
  credibility   smallint,
  impact        smallint,
  importance    smallint,
  coverage      smallint,
  story_key     text,
  event_type    text,                          -- 공시 유형 (T1, 2단계)
  digest_date   date,
  edition       text,
  collected_at  timestamptz not null default now(),
  processed_at  timestamptz
);
create index if not exists articles_status_idx on articles (status, published_at desc);
create index if not exists articles_digest_idx on articles (digest_date);
create index if not exists articles_tickers_idx on articles using gin (tickers);

-- 2) 브리핑·리서치 리포트
create table if not exists reports (
  id          bigint generated by default as identity primary key,
  report_key  text not null unique,           -- briefing:2026-11-13:07:00, research:...
  kind        text not null,                  -- briefing / research
  title       text,
  body        text,
  tickers     jsonb default '[]'::jsonb,
  created_at  timestamptz not null default now()
);

-- 3) 지식베이스
create table if not exists kb_chunks (
  id            bigint generated by default as identity primary key,
  chunk_key     text not null unique,         -- article:123, briefing:..., research:...#2
  kind          text not null,                -- news / filing / data / briefing / research / qa
  is_ai         boolean not null default false, -- AI 해석이면 true (브리핑, Q&A 등)
  tier          text,
  source_grade  text,
  market        text,
  tickers       jsonb default '[]'::jsonb,
  source        text,
  url           text,
  published_at  timestamptz,
  content       text not null,
  embedding     extensions.vector(768) not null,
  created_at    timestamptz not null default now()
);
create index if not exists kb_embedding_idx on kb_chunks using hnsw (embedding extensions.vector_cosine_ops);
create index if not exists kb_tickers_idx on kb_chunks using gin (tickers);
create index if not exists kb_published_idx on kb_chunks (published_at desc);

-- 4) 2단계 이후에 쓰는 표 (미리 만들어 둠)
create table if not exists watchlist (
  market    text not null,                    -- KR / US
  code      text not null,                    -- 005930 / NVDA
  name      text not null,
  added_at  timestamptz not null default now(),
  primary key (market, code)
);
create table if not exists symbols (            -- 종목 사전
  market     text not null,
  code       text not null,
  name       text not null,
  corp_code  text,                            -- DART 고유번호
  cik        text,                            -- SEC CIK
  updated_at timestamptz not null default now(),
  primary key (market, code)
);
create index if not exists symbols_name_idx on symbols (name);
create table if not exists cursors (            -- 공시 수집 커서 등
  key        text primary key,
  value      text,
  updated_at timestamptz not null default now()
);

-- 5) 함수
-- 수집 워크플로: 후보 주소 중 이미 저장된 것
create or replace function existing_url_keys(keys text[])
returns jsonb language sql stable
set search_path = public
as $$
  select jsonb_build_object('keys', coalesce(jsonb_agg(url_key), '[]'::jsonb))
  from articles where url_key = any(keys);
$$;

-- 3단계 /ask, 리서치 과거 맥락에서 사용
create or replace function match_kb(
  query_embedding extensions.vector(768),
  match_count     int default 12,
  filter_codes    text[] default null,         -- 종목코드나 종목명
  since           timestamptz default null,
  include_ai      boolean default true
)
returns table (chunk_key text, kind text, is_ai boolean, source text, url text, published_at timestamptz, content text, similarity float)
language sql stable
set search_path = public, extensions
as $$
  select k.chunk_key, k.kind, k.is_ai, k.source, k.url, k.published_at, k.content,
         1 - (k.embedding <=> query_embedding) as similarity
  from kb_chunks k
  where (since is null or k.published_at >= since)
    and (include_ai or not k.is_ai)
    and (filter_codes is null or exists (
          select 1 from jsonb_array_elements(k.tickers) t
          where t->>'code' = any(filter_codes) or t->>'name' = any(filter_codes)))
  order by k.embedding <=> query_embedding
  limit match_count;
$$;

-- 6) 보안: 공개 키(anon)로는 아무것도 못 읽게 막음. n8n은 서버 키라 영향 없음
alter table articles  enable row level security;
alter table reports   enable row level security;
alter table kb_chunks enable row level security;
alter table watchlist enable row level security;
alter table symbols   enable row level security;
alter table cursors   enable row level security;
revoke execute on function existing_url_keys(text[]) from public, anon, authenticated;
revoke execute on function match_kb(extensions.vector, int, text[], timestamptz, boolean) from public, anon, authenticated;
grant execute on function existing_url_keys(text[]) to service_role;
grant execute on function match_kb(extensions.vector, int, text[], timestamptz, boolean) to service_role;
